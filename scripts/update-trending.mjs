// Fetches live data from TMDB and writes assets/js/trending.js:
// this week's trending titles, what's popular on Netflix and Prime Video in India,
// and the TMDB audience score + rating count for every title we have reviewed.
// Run by .github/workflows/update-trending.yml. Locally: TMDB_API_KEY=... node scripts/update-trending.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = new URL("../assets/js/trending.js", import.meta.url);
const DATA = new URL("../assets/js/data.js", import.meta.url);
const LIMIT = 12;
const ANIMATION = 16;
const REGION = "IN";
const PROVIDERS = { NETFLIX: 8, PRIME: 119 }; // TMDB watch-provider ids (Netflix, Amazon Prime Video)

export function toItem(r) {
  if (!["movie", "tv"].includes(r.media_type) || !r.poster_path) return null;
  const isTv = r.media_type === "tv";
  const anime = isTv && r.genre_ids?.includes(ANIMATION) && r.origin_country?.includes("JP");
  return {
    title: isTv ? r.name : r.title,
    type: anime ? "Anime" : isTv ? "Series" : "Movie",
    year: (isTv ? r.first_air_date : r.release_date)?.slice(0, 4) || "",
    score: r.vote_count ? Math.round(r.vote_average * 10) / 10 : null,
    votes: r.vote_count || 0,
    poster: `https://image.tmdb.org/t/p/w342${r.poster_path}`,
    url: `https://www.themoviedb.org/${r.media_type}/${r.id}`
  };
}

// Discover results don't say whether they are movies or TV, so tag them, then interleave by popularity.
export function mergeByPopularity(movies, tv) {
  return [...movies.map((r) => ({ ...r, media_type: "movie" })), ...tv.map((r) => ({ ...r, media_type: "tv" }))]
    .sort((a, b) => b.popularity - a.popularity)
    .map(toItem).filter(Boolean).slice(0, LIMIT);
}

function client(key) {
  // TMDB gives two kinds of credentials: a short v3 API key or a long v4 read access token.
  const isToken = key.length > 40;
  return async (path, params = {}) => {
    const qs = new URLSearchParams({ language: "en-US", ...params, ...(isToken ? {} : { api_key: key }) });
    const res = await fetch(`https://api.themoviedb.org/3/${path}?${qs}`, { headers: isToken ? { Authorization: `Bearer ${key}` } : {} });
    if (!res.ok) throw new Error(`TMDB ${path} failed: ${res.status} ${await res.text()}`);
    return res.json();
  };
}

async function main() {
  const key = process.env.TMDB_API_KEY;
  if (!key) throw new Error("TMDB_API_KEY is not set");
  const tmdb = client(key);

  const out = { TRENDING: (await tmdb("trending/all/week")).results.map(toItem).filter(Boolean).slice(0, LIMIT) };
  for (const [name, provider] of Object.entries(PROVIDERS)) {
    const params = { watch_region: REGION, with_watch_providers: provider, sort_by: "popularity.desc" };
    const [movies, tv] = await Promise.all([tmdb("discover/movie", params), tmdb("discover/tv", params)]);
    out[name] = mergeByPopularity(movies.results, tv.results);
  }
  // Never overwrite good lists with empty ones if TMDB returns something odd.
  for (const [name, list] of Object.entries(out)) {
    if (list.length < 4) throw new Error(`${name}: only ${list.length} usable results, keeping the old data`);
  }

  const titles = new Function(readFileSync(DATA, "utf8") + "; return TITLES;")();
  const audience = {};
  for (const t of titles.filter((t) => t.tmdb)) {
    const d = await tmdb(t.tmdb);
    const name = d.name || d.title;
    if (name.toLowerCase() !== t.title.toLowerCase()) console.warn(`Check tmdb id for ${t.id}: TMDB calls it "${name}"`);
    audience[t.id] = { score: Math.round(d.vote_average * 10) / 10, votes: d.vote_count };
  }

  const today = new Date().toISOString().slice(0, 10);
  writeFileSync(OUT, `// Generated by scripts/update-trending.mjs. Do not edit by hand.
const TRENDING_UPDATED = "${today}";
const TRENDING = ${JSON.stringify(out.TRENDING, null, 2)};
const NETFLIX = ${JSON.stringify(out.NETFLIX, null, 2)};
const PRIME = ${JSON.stringify(out.PRIME, null, 2)};
const AUDIENCE = ${JSON.stringify(audience, null, 2)};
`);
  console.log(`Wrote ${out.TRENDING.length} trending, ${out.NETFLIX.length} Netflix, ${out.PRIME.length} Prime, ${Object.keys(audience).length} audience scores`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}
